import sanitizeHtml from 'sanitize-html'

const componentHtmlOptions: sanitizeHtml.IOptions = {
  allowedTags: [
    'a',
    'body',
    'button',
    'div',
    'footer',
    'h1',
    'h2',
    'h3',
    'head',
    'header',
    'html',
    'image',
    'img',
    'li',
    'link',
    'meta',
    'nav',
    'p',
    'path',
    'span',
    'strong',
    'svg',
    'title',
    'ul',
  ],
  allowedAttributes: {
    '*': [
      'alt',
      'aria-controls',
      'aria-expanded',
      'aria-hidden',
      'aria-label',
      'aria-labelledby',
      'charset',
      'class',
      'color',
      'content',
      'd',
      'data-module',
      'data-qa',
      'data-text-for-hide',
      'data-text-for-show',
      'fill-rule',
      'fill',
      'focusable',
      'height',
      'hidden',
      'href',
      'id',
      'lang',
      'name',
      'rel',
      'role',
      'sizes',
      'src',
      'target',
      'type',
      'viewBox',
      'width',
      'xlink:href',
      'xmlns',
    ],
  },
  allowedSchemes: ['https'],
  allowProtocolRelative: false,
  disallowedTagsMode: 'discard',
  enforceHtmlBoundary: true,
}

export function sanitizeComponentHtml(html: string): string {
  return sanitizeHtml(html, componentHtmlOptions)
}
